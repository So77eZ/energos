import { test, expect } from '@playwright/test'

test('светлые метки, бренды и контакт в футере читаются', async ({ context, page }, testInfo) => {
  await context.addInitScript(() => {
    localStorage.setItem('energos_age_verified', 'true')
    localStorage.setItem('energos_analytics_consent', 'denied')
    localStorage.setItem('energos_gfx', 'low')
    localStorage.setItem('energos_motion_notice', 'dismissed')
    localStorage.setItem('energos_theme', JSON.stringify({ theme: 'light', accent: 'purple', motion: 'off' }))
  })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/')
  const contact = page.getByRole('link', { name: 'contact@energos.fun', exact: true })
  await expect(contact).toHaveAttribute('href', 'mailto:contact@energos.fun')
  await expect(page.locator('.card-brand-name').first()).toHaveCSS('font-weight', '700')
  await expect(page.locator('.hero-brand')).toHaveCSS('font-size', '16px')
  const popular = page.locator('.rail-row').filter({ has: page.locator('.rail-brand', { hasText: 'ФЛЭШ АП' }) })
  await expect(popular.locator('.rail-brand')).toHaveText('ФЛЭШ АП')
  await expect(popular.locator('.rail-name')).toHaveText('Баббл гам со вкусом банана и клубники')
  await expect(popular.locator('.rail-match')).toHaveCSS('font-size', '14px')
  const ratios = await page.locator('.micro-amber, .tag-cyan, .rail-match').evaluateAll(labels => labels.map(label => {
    const style = getComputedStyle(label)
    const rgb = (color: string) => color.match(/[\d.]+/g)!.slice(0, 3).map(Number)
    const luminance = (channels: number[]) => channels.map(c => c / 255 <= 0.04045 ? c / 255 / 12.92 : ((c / 255 + 0.055) / 1.055) ** 2.4).reduce((sum, c, i) => sum + c * [0.2126, 0.7152, 0.0722][i], 0)
    const fg = luminance(rgb(style.color))
    const bg = luminance(label.classList.contains('rail-match') ? [233, 237, 244] : rgb(style.backgroundColor))
    return (Math.max(fg, bg) + 0.05) / (Math.min(fg, bg) + 0.05)
  }))
  expect(ratios.length).toBeGreaterThan(0)
  for (const ratio of ratios) expect(ratio).toBeGreaterThanOrEqual(4.5)
  await page.screenshot({ path: testInfo.outputPath('catalog-light.png') })
  await page.locator('.card').first().scrollIntoViewIfNeeded()
  await page.screenshot({ path: testInfo.outputPath('catalog-cards-light.png') })
  await page.locator('.side-rail .rail-card').first().screenshot({ path: testInfo.outputPath('popular-drinks.png') })
  await page.goto('/drinks?id=8')
  await expect(page.locator('.drink-brand:visible')).toHaveCSS('font-size', '14px')
  await page.screenshot({ path: testInfo.outputPath('drink-brand.png') })
  await page.setViewportSize({ width: 320, height: 800 })
  await contact.scrollIntoViewIfNeeded()
  await expect(contact).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: testInfo.outputPath('footer-mobile.png') })
})
